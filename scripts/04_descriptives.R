suppressMessages(library(psych))
x <- read.csv("derived/hf_models_v2.csv"); vl <- paste0(c("ifeval","bbh","math","gpqa","musr","mmlupro"), "_lg")
sink("out/descriptives_v1.txt")
cat("n models:", nrow(x), "\nLogit-score correlations\n"); print(round(cor(x[, vl]), 2))
m <- mardia(x[, vl], plot = FALSE); cat("\nMardia skewness", m$b1p, "kurtosis", m$b2p, "p(skew)", m$p.skew, "p(kurt)", m$p.kurt, "\n")
g <- factor(x$base); n <- nrow(x); ng <- nlevels(g); n0 <- (n - sum(table(g)^2) / n) / (ng - 1)
icc <- sapply(vl, function(v) { y <- x[[v]]; k <- table(g); mj <- tapply(y, g, mean)
  msb <- sum(k * (mj - mean(y))^2) / (ng - 1); msw <- sum((y - mj[as.character(g)])^2) / (n - ng)
  (msb - msw) / (msb + (n0 - 1) * msw) })
cat("\nIntraclass correlation within base-model lineages (ANOVA estimator, n0 =", round(n0, 3), ")\n"); print(round(icc, 3))
cat("\nModels with any clipped score:", sum(x$any_clip == 1), sprintf("(%.1f%%)", 100 * mean(x$any_clip == 1)), "\n")
sink()
