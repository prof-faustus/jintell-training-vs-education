suppressMessages({library(lavaan)})
# Multigroup Bollen-Stine cluster bootstrap null for invariance fit changes.
# args: data.csv  syntax.txt  which(role|cohort)  R  outfile  seed
args <- commandArgs(TRUE)
x <- read.csv(args[1]); m <- paste(readLines(args[2]), collapse = "\n")
which <- args[3]; R <- as.integer(args[4]); outf <- args[5]; set.seed(as.integer(args[6])); mode <- if (length(args) >= 7) args[7] else "exact"
ind <- c("ifeval_lg","bbh_lg","math_lg","gpqa_lg","musr_lg","mmlupro_lg")
if (which == "role") {
  x$grp <- ifelse(x$type %in% c("pretrained","continuously pretrained"), "pretrained",
           ifelse(x$type %in% c("fine-tuned on domain-specific datasets","chat models (RLHF, DPO, IFT, ...)"), "finetuned", NA))
  d <- x[!is.na(x$grp), ]; d$cl <- d$base
} else {
  d <- x[x$type %in% c("pretrained","continuously pretrained") & !is.na(x$upload_year), ]
  d$grp <- ifelse(d$upload_year <= 2023, "c2022_23", ifelse(d$upload_year == 2024, "c2024", "c2025"))
  d$cl <- sub("/.*", "", d$model)
}
d$grp <- factor(d$grp); d <- d[complete.cases(d[, ind]), ]
eqs <- list(configural = "", metric = "loadings", scalar = c("loadings","intercepts"),
            strict = c("loadings","intercepts","residuals"))
fm <- c("chisq.scaled","df","cfi.robust","rmsea.robust","srmr")
fitseq <- function(dd) {
  out <- sapply(names(eqs), function(k) {
    f <- try(cfa(m, data = dd, group = "grp", estimator = "MLR", cluster = "cl", group.equal = eqs[[k]]), silent = TRUE)
    if (inherits(f, "try-error") || !lavInspect(f, "converged")) return(rep(NA, length(fm)))
    as.numeric(fitMeasures(f, fm)) })
  rownames(out) <- fm; out }
obs <- fitseq(d)
# Bollen-Stine transform to the strict-model implied moments, per group
mgen <- if (mode == "ext") paste(readLines("out/m5_syntax_logit_v1.txt"), collapse = "\n") else m
fs <- cfa(mgen, data = d, group = "grp", estimator = "MLR", cluster = "cl", group.equal = eqs$strict)
imp <- lavInspect(fs, "implied"); lv <- levels(d$grp)
fc <- cfa(m, data = d, group = "grp", estimator = "MLR", cluster = "cl"); impc <- lavInspect(fc, "implied")
msqrt <- function(S, inv = FALSE) { e <- eigen(S, symmetric = TRUE); v <- if (inv) 1/sqrt(e$values) else sqrt(e$values); e$vectors %*% diag(v) %*% t(e$vectors) }
dt <- d; alpha_used <- rep(NA, length(lv))
for (gi in seq_along(lv)) {
  r <- dt$grp == lv[gi]; X <- as.matrix(dt[r, ind]); S <- cov(X) * (nrow(X) - 1) / nrow(X)
  Sig <- imp[[gi]]$cov[ind, ind]; mu <- imp[[gi]]$mean[ind]
  if (mode == "misfit") { E <- S - impc[[gi]]$cov[ind, ind]; a <- 1
    while (min(eigen(Sig + a * E, symmetric = TRUE)$values) <= 1e-3 && a > 0) a <- a - 0.05
    Sig <- Sig + a * E; mu <- mu + a * (colMeans(X) - impc[[gi]]$mean[ind])
    alpha_used[gi] <- a; cat("group", lv[gi], "misfit share retained alpha =", a, "min eigenvalue:", min(eigen(Sig, symmetric = TRUE)$values), "\n") }
  Z <- sweep(X, 2, colMeans(X)) %*% msqrt(S, TRUE) %*% msqrt(Sig)
  dt[r, ind] <- sweep(Z, 2, mu, "+") }
chk <- fitseq(dt)  # should show near-perfect fit at every level
res <- matrix(NA, R, 9, dimnames = list(NULL, c("dCFI_m","dCFI_s","dCFI_t","dRMSEA_m","dRMSEA_s","dRMSEA_t","dSRMR_m","dSRMR_s","dSRMR_t")))
t0 <- Sys.time()
for (b in 1:R) {
  bb <- do.call(rbind, lapply(lv, function(g) {
    dg <- dt[dt$grp == g, ]; cls <- unique(dg$cl); pick <- sample(cls, length(cls), replace = TRUE)
    do.call(rbind, lapply(seq_along(pick), function(j) { z <- dg[dg$cl == pick[j], ]; z$cl <- paste0(g, "_", j); z })) }))
  bb$grp <- factor(bb$grp, levels = lv)
  f <- fitseq(bb)
  res[b, ] <- c(diff(f["cfi.robust", ]), diff(f["rmsea.robust", ]), diff(f["srmr", ]))
}
sink(outf)
cat("Null mode:", mode, "| misfit share retained per group:", paste(lv, alpha_used, collapse = "; "), "\n"); cat("Design:", which, " R =", R, " groups:", paste(lv, table(d$grp), collapse = "; "), " clusters:", length(unique(d$cl)), "\n")
cat("Elapsed:", format(Sys.time() - t0), "\n\nObserved fit sequence\n"); print(round(obs, 4))
cat("\nTransformed data (exact: analysis model fits perfectly at every level; ext: data generated by the strict-invariant extended model, analysed with M4)\n"); print(round(chk, 4))
od <- c(diff(obs["cfi.robust", ]), diff(obs["rmsea.robust", ]), diff(obs["srmr", ]))
names(od) <- colnames(res)
cat("\nConverged replicates:", sum(complete.cases(res)), "of", R, "\n")
q <- apply(res, 2, quantile, c(.01, .05, .5, .95, .99), na.rm = TRUE)
print(round(rbind(q, observed = od), 4))
# one-sided empirical p: CFI drops (more negative = worse); RMSEA/SRMR rises (more positive = worse)
p <- c(sapply(1:3, function(j) mean(res[, j] <= od[j], na.rm = TRUE)), sapply(4:9, function(j) mean(res[, j] >= od[j], na.rm = TRUE)))
names(p) <- colnames(res); cat("\nEmpirical p (share of null replicates at least as bad as observed)\n"); print(round(p, 4))
sink()
write.csv(res, sub("\\.txt$", "_reps.csv", outf), row.names = FALSE)
